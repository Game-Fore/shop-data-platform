{#
  Заказы, по которым события пришли в ClickHouse только что. Для dbt build на живом потоке:
  модели собираются по очереди, поэтому staging, прочитанный секундами позже fct_orders, уже
  новее его снимка. Плюс заказ и его позиции могут попасть в разные батчи consumer'а.
  Сверки такие заказы пропускают: это задержка пайплайна, а не ошибка данных.
  Окно считается по времени прихода (_ingested_at), а не по бизнес-времени: старый заказ может
  сменить статус прямо сейчас, а история из backfill приходит со старыми датами.
#}
{% macro settling_order_ids() -%}
    (
        select order_id
        from {{ ref('stg_order_events') }}
        where _ingested_at >= now() - toIntervalMinute({{ var('settling_window_minutes') }})
    )
{%- endmacro %}
